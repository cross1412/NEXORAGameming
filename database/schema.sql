CREATE DATABASE IF NOT EXISTS nexora_gaming CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE nexora_gaming;

CREATE TABLE users (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(190) NOT NULL UNIQUE,
  phone VARCHAR(20),
  password_hash VARCHAR(255) NOT NULL,
  display_name VARCHAR(100),
  stand_rank ENUM('E','C','A','S') NOT NULL DEFAULT 'E',
  nexora_coins INT UNSIGNED NOT NULL DEFAULT 0,
  total_spent DECIMAL(12,2) NOT NULL DEFAULT 0,
  role ENUM('customer','super_admin','order_staff','marketing') NOT NULL DEFAULT 'customer',
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE user_addresses (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT UNSIGNED NOT NULL,
  label VARCHAR(50),
  recipient_name VARCHAR(100) NOT NULL,
  phone VARCHAR(20) NOT NULL,
  address_line TEXT NOT NULL,
  province VARCHAR(100),
  postal_code VARCHAR(10),
  is_primary BOOLEAN DEFAULT FALSE,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE categories (id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,name VARCHAR(100) NOT NULL UNIQUE,slug VARCHAR(100) UNIQUE,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP) ENGINE=InnoDB;
CREATE TABLE brands (id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,name VARCHAR(100) NOT NULL UNIQUE,slug VARCHAR(100) UNIQUE,created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP) ENGINE=InnoDB;
CREATE TABLE products (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, category_id BIGINT UNSIGNED NOT NULL, brand_id BIGINT UNSIGNED NOT NULL,
  sku VARCHAR(100) NOT NULL UNIQUE, name VARCHAR(200) NOT NULL, description TEXT, image_url VARCHAR(500),
  price DECIMAL(12,2) NOT NULL, old_price DECIMAL(12,2), `rank` ENUM('S','A','B','C') DEFAULT 'C',
  pre_order BOOLEAN DEFAULT FALSE, deposit_percent TINYINT UNSIGNED DEFAULT 0,
  power_speed TINYINT UNSIGNED, power_precision TINYINT UNSIGNED, power_durability TINYINT UNSIGNED, power_value TINYINT UNSIGNED,
  pros JSON, cons JSON, active BOOLEAN DEFAULT TRUE,
  FOREIGN KEY (category_id) REFERENCES categories(id), FOREIGN KEY (brand_id) REFERENCES brands(id)
) ENGINE=InnoDB;

CREATE TABLE product_variants (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, product_id BIGINT UNSIGNED NOT NULL, name VARCHAR(100) NOT NULL,
  sku_variant VARCHAR(100) UNIQUE, stock INT UNSIGNED NOT NULL DEFAULT 0, price_delta DECIMAL(12,2) DEFAULT 0,
  FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE orders (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_number VARCHAR(40) NOT NULL UNIQUE, user_id BIGINT UNSIGNED,
  status ENUM('demo','pending','paid','processing','shipping','delivered','cancelled','refunded') DEFAULT 'pending',
  subtotal DECIMAL(12,2) NOT NULL, shipping_fee DECIMAL(12,2) DEFAULT 0, discount DECIMAL(12,2) DEFAULT 0, total DECIMAL(12,2) NOT NULL,
  payment_method VARCHAR(40), shipping_tracking VARCHAR(100), slip_url VARCHAR(500),
  shipping_address JSON, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE order_items (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, order_id BIGINT UNSIGNED NOT NULL, product_id BIGINT UNSIGNED,
  variant_id BIGINT UNSIGNED, quantity INT UNSIGNED NOT NULL, unit_price DECIMAL(12,2) NOT NULL,
  FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE,
  FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE SET NULL,
  FOREIGN KEY (variant_id) REFERENCES product_variants(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE vouchers (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(50) NOT NULL UNIQUE, discount_type ENUM('fixed','percent','free_shipping') NOT NULL,
  discount_value DECIMAL(12,2) NOT NULL, minimum_order DECIMAL(12,2) DEFAULT 0, usage_limit INT UNSIGNED,
  starts_at DATETIME, ends_at DATETIME, active BOOLEAN DEFAULT TRUE
) ENGINE=InnoDB;

CREATE TABLE user_vouchers (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, voucher_id BIGINT UNSIGNED NOT NULL,
  used_at DATETIME, UNIQUE KEY unique_key (user_id,voucher_id),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE, FOREIGN KEY (voucher_id) REFERENCES vouchers(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE reviews (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, product_id BIGINT UNSIGNED NOT NULL,
  rating TINYINT UNSIGNED NOT NULL CHECK (rating BETWEEN 1 AND 5), comment TEXT, images JSON, reward_coins INT UNSIGNED DEFAULT 0,
  approved BOOLEAN DEFAULT FALSE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE, FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE arcade_logs (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED, game_type VARCHAR(50) NOT NULL,
  score INT UNSIGNED DEFAULT 0, reward VARCHAR(100), ip_hash CHAR(64), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE pose_challenges (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, image_url VARCHAR(500) NOT NULL,
  status ENUM('pending','approved','rejected') DEFAULT 'pending', reward_coins INT UNSIGNED DEFAULT 500,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE affiliate_stats (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, referral_code VARCHAR(50) NOT NULL UNIQUE,
  referred_users INT UNSIGNED DEFAULT 0, referred_sales DECIMAL(12,2) DEFAULT 0, commission_percent DECIMAL(5,2) DEFAULT 3,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE admin_logs (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, admin_id BIGINT UNSIGNED, action VARCHAR(100) NOT NULL,
  entity_type VARCHAR(50), entity_id VARCHAR(100), details JSON, ip_hash CHAR(64),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (admin_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;
